    private fun normalizeHistoryTurns(
        history: List<ChatTurn>,
        allowLeadingAssistant: Boolean,
        maxTurns: Int = 10
    ): List<ChatTurn> {
        val merged = mutableListOf<ChatTurn>()
        var seenUser = allowLeadingAssistant
        history.takeLast(maxTurns).forEach { turn ->
            val clean = turn.text.trim()
            if (clean.isEmpty()) return@forEach
            val role = if (turn.role.equals("user", ignoreCase = true)) "user" else "assistant"
            if (!seenUser && role != "user") return@forEach
            if (role == "user") seenUser = true
            val last = merged.lastOrNull()
            if (last != null && last.role == role) {
                merged[merged.lastIndex] = last.copy(text = "${last.text}\n\n$clean")
            } else {
                merged.add(ChatTurn(role, clean))
            }
        }
        return merged
    }

    private fun buildConversationTurns(
        studyContext: String,
        history: List<ChatTurn>,
        question: String
    ): List<ChatTurn> {
        val merged = mutableListOf<ChatTurn>()
        fun appendTurn(role: String, text: String) {
            val clean = text.trim()
            if (clean.isEmpty()) return
            val last = merged.lastOrNull()
            if (last != null && last.role == role) {
                merged[merged.lastIndex] = last.copy(text = "${last.text}\n\n$clean")
            } else {
                merged.add(ChatTurn(role, clean))
            }
        }

        if (studyContext.isNotBlank()) {
            appendTurn(
                "user",
                "DADOS REAIS DO ESTUDANTE NO APP STUDYDOCK (apenas para consulta factual):\n${studyContext.trim()}"
            )
            appendTurn(
                "assistant",
                "Entendido. Recebi os dados atualizados de estudo, Anki, notas e tarefas."
            )
        }
        normalizeHistoryTurns(
            history = history,
            allowLeadingAssistant = studyContext.isNotBlank(),
            maxTurns = 10
        ).forEach { turn ->
            appendTurn(turn.role, turn.text)
        }
        appendTurn("user", question)
        return merged
    }

    private data class JsonHttpResult(val code: Int, val json: JSONObject)

    internal fun validateEndpointUrl(url: URL) {
        val isLoopbackHttp = url.protocol == "http" && url.host in setOf("10.0.2.2", "localhost", "127.0.0.1")
        require(url.userInfo == null && (url.protocol == "https" || isLoopbackHttp)) {
            "Use uma URL HTTPS sem credenciais na URL para manter a conexão protegida."
        }
    }

    internal fun readStreamBounded(
        stream: InputStream?,
        maxBytes: Int = MAX_HTTP_RESPONSE_BYTES,
        failOnOverflow: Boolean = true
    ): String {
        if (stream == null) return ""
        stream.use { input ->
            val out = ByteArrayOutputStream()
            val buffer = ByteArray(8192)
            var total = 0
            while (true) {
                val read = input.read(buffer)
                if (read == -1) break
                val nextTotal = total + read
                if (nextTotal > maxBytes) {
                    if (failOnOverflow) {
                        throw IllegalStateException("Resposta do servidor excedeu o limite permitido (${maxBytes / 1024} KB).")
                    }
                    val remaining = (maxBytes - total).coerceAtLeast(0)
                    if (remaining > 0) out.write(buffer, 0, remaining)
                    break
                }
                out.write(buffer, 0, read)
                total = nextTotal
            }
            return out.toByteArray().toString(Charsets.UTF_8)
        }
    }

    private fun parseEndpointUrl(providerLabel: String, endpoint: String): URL = try {
        URL(endpoint)
    } catch (e: MalformedURLException) {
        StudyLog.w(TAG, "$providerLabel invalid URL: ${e::class.java.simpleName}")
        throw e
    }

    internal fun executePostJsonRequest(
        providerLabel: String,
        url: URL,
        bodyBytes: ByteArray,
        headers: Map<String, String>,
        followRedirects: Boolean = false
    ): Pair<Int, String> {
        val connection = (url.openConnection() as HttpURLConnection).apply {
            requestMethod = "POST"
            connectTimeout = 15_000
            readTimeout = 60_000
            instanceFollowRedirects = followRedirects
            doOutput = true
            setFixedLengthStreamingMode(bodyBytes.size)
            setRequestProperty("Content-Type", "application/json; charset=utf-8")
            headers.forEach { (key, value) -> setRequestProperty(key, value) }
        }
        try {
            connection.outputStream.use { it.write(bodyBytes) }
            val code = connection.responseCode
            if (!followRedirects && code in 300..399) {
                StudyLog.w(TAG, "$providerLabel HTTP redirect blocked (status=$code)")
                throw IllegalStateException("Redirecionamento HTTP ($code) bloqueado por segurança em $providerLabel.")
            }
            val responseText = if (code in 200..299) {
                readStreamBounded(connection.inputStream, MAX_HTTP_RESPONSE_BYTES, failOnOverflow = true)
            } else {
                readStreamBounded(connection.errorStream, MAX_HTTP_ERROR_BYTES, failOnOverflow = false)
            }
            return code to responseText
        } catch (e: IOException) {
            StudyLog.w(TAG, "$providerLabel IO failure: ${e::class.java.simpleName}")
            throw e
        } finally {
            connection.disconnect()
        }
    }

    private fun postJson(
        providerLabel: String,
        url: URL,
        payload: JSONObject,
        headers: Map<String, String>,
        followRedirects: Boolean = false
    ): JsonHttpResult {
        val (code, responseText) = executePostJsonRequest(
            providerLabel = providerLabel,
            url = url,
            bodyBytes = payload.toString().toByteArray(Charsets.UTF_8),
            headers = headers,
            followRedirects = followRedirects
        )
        val json = try {
            JSONObject(responseText.ifBlank { "{}" })
        } catch (e: JSONException) {
            StudyLog.w(TAG, "$providerLabel non-JSON response (http=$code, error=${e::class.java.simpleName})")
            if (code !in 200..299) {
                return JsonHttpResult(code, JSONObject())
            }
            throw IllegalStateException("Resposta inválida de $providerLabel ($code).", e)
        }
        if (code !in 200..299) {
            val errObj = json.optJSONObject("error")
            val errType = errObj?.optString("status").orEmpty()
                .ifBlank { errObj?.optString("type").orEmpty() }
                .ifBlank { errObj?.optString("code").orEmpty() }
                .ifBlank { "HTTP_$code" }
            StudyLog.w(TAG, "$providerLabel HTTP failure: status=$code, type=$errType")
        }
        return JsonHttpResult(code, json)
    }

    private fun callGeminiDirect(
        apiKey: String,
        model: String,
        systemInstructions: String,
        history: List<ChatTurn>,
        question: String,
        studyContext: String
    ): String {
        require(apiKey.isNotBlank()) { "Informe sua Gemini API Key nas configurações do Tutor." }
        val cleanModel = model.removePrefix("models/").trim().ifBlank { "gemini-2.5-flash" }
        require(cleanModel.matches(validGeminiModelRegex) && !cleanModel.contains("..")) {
            "Nome de modelo Gemini inválido."
        }
        val endpoint = "https://generativelanguage.googleapis.com/v1beta/models/$cleanModel:generateContent"
        val url = parseEndpointUrl("Gemini", endpoint)

        val contents = JSONArray()
        buildConversationTurns(studyContext, history, question).forEach { turn ->
            contents.put(
                JSONObject()
                    .put("role", if (turn.role == "user") "user" else "model")
                    .put("parts", JSONArray().put(JSONObject().put("text", turn.text)))
            )
        }

        val payload = JSONObject()
            .put("system_instruction", JSONObject().put("parts", JSONArray().put(JSONObject().put("text", systemInstructions))))
            .put("contents", contents)
            .put("generationConfig", JSONObject().put("temperature", 0.65).put("maxOutputTokens", 4096))

        val result = postJson(
            providerLabel = "Gemini",
            url = url,
            payload = payload,
            headers = mapOf("x-goog-api-key" to apiKey)
        )
        if (result.code !in 200..299) {
            val errMsg = result.json.optJSONObject("error")?.optString("message").orEmpty()
            throw IllegalStateException(errMsg.ifBlank { "Erro na API Gemini (${result.code})." })
        }
        val candidates = result.json.optJSONArray("candidates") ?: JSONArray()
        val parts = candidates.optJSONObject(0)?.optJSONObject("content")?.optJSONArray("parts") ?: JSONArray()
        val sb = StringBuilder()
        for (i in 0 until parts.length()) {
            val t = parts.optJSONObject(i)?.optString("text").orEmpty()
            if (t.isNotEmpty()) sb.append(t)
        }
        return sb.toString().ifBlank { "A resposta veio vazia. Tente novamente." }
    }

    internal fun callOpenAiCompatible(
        apiKey: String,
        baseUrl: String,
        model: String,
        systemInstructions: String,
        history: List<ChatTurn>,
        question: String,
        studyContext: String
    ): String {
        require(apiKey.isNotBlank()) { "Informe sua API Key nas configurações do Tutor." }
        val normalized = baseUrl.trim().trimEnd('/')
        val endpoint = if (normalized.endsWith("/chat/completions")) normalized else "$normalized/chat/completions"
        val url = parseEndpointUrl("OpenAI-compat", endpoint)
        validateEndpointUrl(url)

        val messages = JSONArray()
        messages.put(JSONObject().put("role", "system").put("content", systemInstructions))
        buildConversationTurns(studyContext, history, question).forEach { turn ->
            messages.put(JSONObject().put("role", turn.role).put("content", turn.text))
        }

        val payload = JSONObject()
            .put("model", model)
            .put("messages", messages)
            .put("max_tokens", 4096)

        val result = postJson(
            providerLabel = "OpenAI-compat",
            url = url,
            payload = payload,
            headers = mapOf("Authorization" to "Bearer $apiKey"),
            followRedirects = false
        )
        if (result.code !in 200..299) {
            val errMsg = result.json.optJSONObject("error")?.optString("message") ?: result.json.optString("error")
            throw IllegalStateException(errMsg.ifBlank { "O servidor respondeu com erro (${result.code})." })
        }
        val content = result.json.optJSONArray("choices")
            ?.optJSONObject(0)
            ?.optJSONObject("message")
            ?.optString("content")
            .orEmpty()
        return content.ifBlank { "A resposta veio vazia. Tente novamente." }
    }

    internal fun callCustomProxy(
        baseUrl: String,
        accessToken: String,
        systemInstructions: String,
        history: List<ChatTurn>,
        question: String,
        studyContext: String
    ): String {
        require(accessToken.isNotBlank()) { "Token de acesso do proxy não configurado." }
        val normalized = baseUrl.trim().trimEnd('/')
        val endpoint = if (normalized.endsWith("/chat")) normalized else "$normalized/chat"
        val url = parseEndpointUrl("Proxy", endpoint)
        validateEndpointUrl(url)

        val historyArray = JSONArray()
        normalizeHistoryTurns(
            history = history,
            allowLeadingAssistant = studyContext.isNotBlank(),
            maxTurns = 10
        ).forEach { turn ->
            historyArray.put(
                JSONObject()
                    .put("role", turn.role)
                    .put("content", turn.text.take(4000))
            )
        }

        val payload = JSONObject()
            .put("system_instructions", systemInstructions)
            .put("question", question.trim())
            .put("history", historyArray)
        if (studyContext.isNotBlank()) {
            payload.put("study_context", studyContext.trim())
        }

        val result = postJson(
            providerLabel = "Proxy",
            url = url,
            payload = payload,
            headers = mapOf("Authorization" to "Bearer $accessToken"),
            followRedirects = false
        )
        if (result.code !in 200..299) {
            throw IllegalStateException(result.json.optString("error").ifBlank { "O serviço respondeu com erro (${result.code})." })
        }
        return result.json.optString("answer").ifBlank { "A resposta veio vazia. Tente novamente." }
    }
