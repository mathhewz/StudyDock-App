    fun layoutCanvasBoard(
        canvas: GeneratedStudyObject.CanvasObj,
        noteIdsByTitle: Map<String, Long> = emptyMap()
    ): BuiltCanvasBoard {
        val defaultPalette = listOf(
            0xFF8B5CF6.toInt(),
            0xFF3B82F6.toInt(),
            0xFF06B6D4.toInt(),
            0xFF10B981.toInt(),
            0xFFF59E0B.toInt(),
            0xFFEC4899.toInt()
        )
        val colorMap = mapOf(
            "violet" to 0xFF8B5CF6.toInt(),
            "blue" to 0xFF3B82F6.toInt(),
            "cyan" to 0xFF06B6D4.toInt(),
            "green" to 0xFF10B981.toInt(),
            "lime" to 0xFF84CC16.toInt(),
            "amber" to 0xFFF59E0B.toInt(),
            "orange" to 0xFFF97316.toInt(),
            "red" to 0xFFEF4444.toInt(),
            "rose" to 0xFFEC4899.toInt(),
            "indigo" to 0xFF6366F1.toInt(),
            "slate" to 0xFF64748B.toInt()
        )

        val nodes = canvas.nodes
        if (nodes.isEmpty()) return BuiltCanvasBoard(emptyList(), emptyList())

        data class PlacedBox(val x: Float, val y: Float, val w: Float, val h: Float)

        val widths = FloatArray(nodes.size) { 250f }
        val heights = FloatArray(nodes.size) { idx ->
            val n = nodes[idx]
            val textLines = if (n.text.isBlank()) 1 else n.text.lines().sumOf { line -> max(1, (line.length + 27) / 28) }
            (92f + textLines * 20f).coerceIn(132f, 240f)
        }
        val placed = arrayOfNulls<PlacedBox>(nodes.size)
        val idxById = nodes.withIndex().associate { (i, n) -> n.id to i }

        when (canvas.layout.lowercase(Locale.ROOT)) {
            "grid" -> {
                val cols = if (nodes.size <= 4) 2 else 3
                val hGap = 54f
                val vGap = 64f
                var cursorY = 0f
                nodes.indices.chunked(cols).forEach { rowIndices ->
                    val rowW = rowIndices.sumOf { widths[it].toDouble() }.toFloat() + hGap * max(0, rowIndices.size - 1)
                    var cursorX = -rowW / 2f
                    val rowMaxH = rowIndices.maxOf { heights[it] }
                    rowIndices.forEach { i ->
                        placed[i] = PlacedBox(cursorX, cursorY, widths[i], heights[i])
                        cursorX += widths[i] + hGap
                    }
                    cursorY += rowMaxH + vGap
                }
            }
            "radial" -> {
                val rootIdx = nodes.indices.firstOrNull { i -> canvas.edges.none { it.to == nodes[i].id } } ?: 0
                placed[rootIdx] = PlacedBox(-widths[rootIdx] / 2f, -heights[rootIdx] / 2f, widths[rootIdx], heights[rootIdx])
                val depth = IntArray(nodes.size) { -1 }
                depth[rootIdx] = 0
                val queue = ArrayDeque<Int>().apply { add(rootIdx) }
                while (queue.isNotEmpty()) {
                    val u = queue.removeFirst()
                    val uId = nodes[u].id
                    canvas.edges.forEach { edge ->
                        if (edge.from == uId) {
                            val v = idxById[edge.to]
                            if (v != null && depth[v] == -1) {
                                depth[v] = depth[u] + 1
                                queue.add(v)
                            }
                        }
                    }
                }
                val maxDepth = depth.max().coerceAtLeast(1)
                for (d in nodes.indices) if (depth[d] == -1) depth[d] = if (nodes.size <= 2) 1 else maxDepth
                val tiers = (1..depth.max().coerceAtLeast(1)).map { lvl -> nodes.indices.filter { depth[it] == lvl } }.filter { it.isNotEmpty() }
                tiers.forEachIndexed { tierPos, tierIndices ->
                    val radius = max(360f + tierPos * 330f, tierIndices.size * 68f)
                    val step = (2.0 * PI) / tierIndices.size.coerceAtLeast(1)
                    tierIndices.forEachIndexed { k, nodeIdx ->
                        val angle = -PI / 2.0 + k * step
                        val cx = (cos(angle) * radius).toFloat()
                        val cy = (sin(angle) * radius).toFloat()
                        placed[nodeIdx] = PlacedBox(cx - widths[nodeIdx] / 2f, cy - heights[nodeIdx] / 2f, widths[nodeIdx], heights[nodeIdx])
                    }
                }
            }
            else -> {
                val depth = IntArray(nodes.size) { -1 }
                val roots = nodes.indices.filter { i -> canvas.edges.none { it.to == nodes[i].id } }.ifEmpty { listOf(0) }
                val queue = ArrayDeque<Int>()
                roots.forEach { r ->
                    depth[r] = 0
                    queue.add(r)
                }
                while (queue.isNotEmpty()) {
                    val u = queue.removeFirst()
                    val uId = nodes[u].id
                    canvas.edges.forEach { edge ->
                        if (edge.from == uId) {
                            val v = idxById[edge.to]
                            if (v != null && depth[v] == -1) {
                                depth[v] = depth[u] + 1
                                queue.add(v)
                            }
                        }
                    }
                }
                val nextTier = (depth.max().takeIf { it >= 0 } ?: 0) + 1
                nodes.indices.forEach { i -> if (depth[i] == -1) depth[i] = nextTier }
                val rows = depth.withIndex()
                    .groupBy({ it.value }, { it.index })
                    .toSortedMap()
                    .values
                    .flatMap { tierIndices -> tierIndices.chunked(3) }

                val hGap = 54f
                val vGap = 82f
                var cursorY = 0f
                rows.forEach { rowIndices ->
                    val rowW = rowIndices.sumOf { widths[it].toDouble() }.toFloat() + hGap * max(0, rowIndices.size - 1)
                    var cursorX = -rowW / 2f
                    val rowMaxH = rowIndices.maxOf { heights[it] }
                    rowIndices.forEach { i ->
                        placed[i] = PlacedBox(cursorX, cursorY, widths[i], heights[i])
                        cursorX += widths[i] + hGap
                    }
                    cursorY += rowMaxH + vGap
                }
            }
        }

        val resolvedBoxes = placed.mapIndexed { idx, box -> box ?: PlacedBox(idx * 290f, 0f, widths[idx], heights[idx]) }
        val minX = resolvedBoxes.minOf { it.x }
        val maxX = resolvedBoxes.maxOf { it.x + it.w }
        val minY = resolvedBoxes.minOf { it.y }
        val maxY = resolvedBoxes.maxOf { it.y + it.h }
        val offsetX = (minX + maxX) / 2f
        val offsetY = (minY + maxY) / 2f

        val builtNodes = nodes.mapIndexed { idx, n ->
            val box = resolvedBoxes[idx]
            val matchedNoteId = noteIdsByTitle[n.title.trim().lowercase(Locale.ROOT)]
            val resolvedType = if (matchedNoteId != null) "note" else "text"
            val colorArgb = colorMap[n.colorName?.lowercase(Locale.ROOT)] ?: defaultPalette[idx % defaultPalette.size]
            BuiltCanvasNode(
                id = n.id,
                type = resolvedType,
                x = box.x - offsetX,
                y = box.y - offsetY,
                width = box.w,
                height = box.h,
                title = n.title,
                text = n.text,
                noteId = matchedNoteId,
                colorArgb = colorArgb
            )
        }
        val builtEdges = canvas.edges.mapIndexed { idx, e ->
            BuiltCanvasEdge(
                id = "e_${idx + 1}",
                fromNode = e.from,
                toNode = e.to,
                label = e.label
            )
        }
        return BuiltCanvasBoard(builtNodes, builtEdges)
    }

