    private fun parseActionFields(
        block: String,
        knownKeys: List<String>,
        stopSwitchingAfterKey: String? = null
    ): Map<String, String> {
        val keySet = knownKeys.map { it.uppercase() }.toSet()
        val lockedKey = stopSwitchingAfterKey?.uppercase()
        val fields = linkedMapOf<String, StringBuilder>()
        var currentKey: String? = null

        block.lines().forEach { line ->
            val match = if (currentKey != null && currentKey == lockedKey) null else fieldHeaderRegex.matchEntire(line)
            val candidateKey = match?.groupValues?.get(1)?.uppercase()
            if (match != null && candidateKey != null && candidateKey in keySet) {
                currentKey = candidateKey
                fields[candidateKey] = StringBuilder(match.groupValues[2])
            } else if (currentKey != null) {
                val sb = fields.getValue(currentKey!!)
                if (sb.isNotEmpty() || line.isNotBlank()) {
                    if (sb.isNotEmpty()) sb.append('\n')
                    sb.append(line)
                }
            }
        }
        return fields.mapValues { (_, sb) -> sb.toString().trim() }
    }

