    fun parseReplyActions(rawAnswer: String): ParsedAssistantReply {
        var working = rawAnswer.replace("\r\n", "\n").replace("\r", "\n")
        var detectedLevel: Int? = null

        levelRegex.find(working)?.let { match ->
            detectedLevel = match.groupValues[1].toIntOrNull()
            working = working.replace(match.value, "")
        }

        val actions = mutableListOf<GeneratedStudyObject>()
        val cleanBuilder = StringBuilder()
        var cursor = 0

        while (cursor < working.length) {
            val openMatch = openActionRegex.find(working, startIndex = cursor) ?: break
            val headerStart = openMatch.range.first
            val bodyStart = openMatch.range.last + 1
            val nextOpen = openActionRegex.find(working, startIndex = bodyStart)
            val searchLimit = nextOpen?.range?.first ?: working.length
            val segment = working.substring(bodyStart, searchLimit)
            val endBounds = findActionBlockEnd(segment)
            if (endBounds == null) {
                cleanBuilder.append(working, cursor, headerStart)
                cursor = searchLimit
                continue
            }

            val prefixChunk = working.substring(cursor, headerStart)
            val fenceLinesCount = fenceLineRegex.findAll(prefixChunk).count()
            val hasUnclosedOpeningFence = (fenceLinesCount % 2 == 1) && openWrapperFenceRegex.containsMatchIn(prefixChunk)
            cleanBuilder.append(
                if (hasUnclosedOpeningFence) openWrapperFenceRegex.replace(prefixChunk, "\n") else prefixChunk
            )
            val kind = openMatch.groupValues[1].uppercase(Locale.ROOT)
            val body = segment.substring(0, endBounds.first).trim()
            parseActionBlock(kind, body)?.let { actions.add(it) }
            var nextCursor = bodyStart + endBounds.second
            if (hasUnclosedOpeningFence && nextCursor < working.length) {
                val tailAfterEnd = working.substring(nextCursor)
                val closeFenceMatch = closeWrapperFenceRegex.find(tailAfterEnd)
                if (closeFenceMatch != null && closeFenceMatch.range.first == 0) {
                    nextCursor += closeFenceMatch.range.last + 1
                }
            }
            cursor = nextCursor
        }

        if (cursor < working.length) {
            cleanBuilder.append(working, cursor, working.length)
        }

        val cleanText = cleanBuilder.toString()
            .replace(tripleNewlineRegex, "\n\n")
            .trim()
        return ParsedAssistantReply(
            cleanText = cleanText.ifBlank { "Pronto! Preparei os itens abaixo para você adicionar ao StudyDock:" },
            actions = actions,
            suggestedFeynmanLevel = detectedLevel
        )
    }

    private fun findActionBlockEnd(segment: String): Pair<Int, Int>? {
        endActionRegex.find(segment)?.let { return it.range.first to (it.range.last + 1) }
        lineClosingRegex.find(segment)?.let { return it.range.first to (it.range.last + 1) }
        trailingClosingRegex.find(segment)?.let { return it.range.first to (it.range.last + 1) }
        return null
    }

    private fun parseActionBlock(kind: String, body: String): GeneratedStudyObject? = when (kind) {
        "FLASHCARD" -> {
            val fields = parseActionFields(body, listOf("FRONT", "BACK", "DECK", "SUBJECT"))
            val front = fields["FRONT"].orEmpty()
            val back = fields["BACK"].orEmpty()
            val deck = fields["DECK"].orEmpty().ifBlank { "Tutor IA" }
            val subject = fields["SUBJECT"]?.takeIf { it.isNotBlank() }
            if (front.isNotBlank() && back.isNotBlank()) {
                GeneratedStudyObject.FlashcardObj(front, back, deck, subject)
            } else {
                null
            }
        }
        "NOTE" -> {
            val fields = parseActionFields(
                body,
                knownKeys = listOf("TITLE", "FOLDER", "TAGS", "CONTENT"),
                stopSwitchingAfterKey = "CONTENT"
            )
            val title = fields["TITLE"].orEmpty().ifBlank { "Nota do Tutor IA" }
            val folder = fields["FOLDER"].orEmpty().ifBlank { "Tutor IA" }
            val tagsRaw = fields["TAGS"].orEmpty()
            val tags = tagsRaw.split(',', ';', ' ')
                .map { it.trim().removePrefix("#") }
                .filter { it.isNotBlank() }
            val content = fields["CONTENT"].orEmpty().ifBlank { "# $title\n\n$body" }
            GeneratedStudyObject.NoteObj(title, folder, tags, content)
        }
        "TASK" -> {
            val fields = parseActionFields(
                body,
                knownKeys = listOf("TITLE", "SUBJECT", "DUE_DAYS", "PRIORITY", "DETAILS"),
                stopSwitchingAfterKey = "DETAILS"
            )
            val title = fields["TITLE"].orEmpty()
            val subject = fields["SUBJECT"]?.takeIf { it.isNotBlank() }
            val dueDays = fields["DUE_DAYS"]?.toIntOrNull()?.coerceIn(0, 365) ?: 1
            val priority = fields["PRIORITY"]?.toIntOrNull()?.coerceIn(1, 4) ?: 2
            val details = fields["DETAILS"].orEmpty()
            if (title.isNotBlank()) {
                GeneratedStudyObject.TaskObj(title, subject, dueDays, priority, details)
            } else {
                null
            }
        }
        "GOAL" -> {
            val fields = parseActionFields(
                body,
                listOf("TITLE", "DAYS", "METRICA", "METRIC", "ALVO", "TARGET", "UNIDADE", "UNIT", "SUBJECT")
            )
            val title = fields["TITLE"].orEmpty()
            val days = fields["DAYS"]?.let(::extractFirstNumber)?.toInt()?.coerceIn(1, 1000) ?: 14
            val rawMetric = (fields["METRICA"] ?: fields["METRIC"]).orEmpty()
            val rawTarget = (fields["ALVO"] ?: fields["TARGET"]).orEmpty()
            val parsedTarget = extractFirstNumber(rawTarget)?.coerceAtLeast(0.0) ?: 0.0
            val rawUnit = (fields["UNIDADE"] ?: fields["UNIT"]).orEmpty()
            val subjectName = fields["SUBJECT"]?.takeIf { it.isNotBlank() }
            val normalizedMetric = normalizeGoalMetric(rawMetric, rawTarget, rawUnit, parsedTarget)
            val resolvedUnit = rawUnit.ifBlank { defaultGoalMetricUnit(normalizedMetric) }
            if (title.isNotBlank()) {
                GeneratedStudyObject.GoalObj(
                    title = title,
                    targetInDays = days,
                    metricType = normalizedMetric,
                    targetValue = if (normalizedMetric == "COUNTDOWN") 0.0 else parsedTarget,
                    metricUnit = resolvedUnit,
                    subjectName = subjectName
                )
            } else {
                null
            }
        }
        "CANVAS" -> parseCanvasBlock(body)
        else -> null
    }

    private fun parseCanvasBlock(body: String): GeneratedStudyObject.CanvasObj? {
        var title = ""
        var summary = ""
        var layout = "tree"
        val nodes = mutableListOf<GeneratedStudyObject.CanvasNodeSpec>()
        val rawEdges = mutableListOf<Triple<String, String, String>>()
        val knownColors = mapOf(
            "violet" to "violet", "purple" to "violet", "roxo" to "violet", "lilac" to "violet",
            "blue" to "blue", "azul" to "blue",
            "cyan" to "cyan", "ciano" to "cyan", "teal" to "cyan",
            "green" to "green", "verde" to "green", "emerald" to "green",
            "lime" to "lime", "lima" to "lime",
            "amber" to "amber", "gold" to "amber", "yellow" to "amber", "amarelo" to "amber",
            "orange" to "orange", "laranja" to "orange",
            "red" to "red", "vermelho" to "red", "crimson" to "red",
            "pink" to "rose", "rose" to "rose", "rosa" to "rose",
            "indigo" to "indigo", "slate" to "slate", "gray" to "slate", "cinza" to "slate"
        )
        val knownTypes = setOf("text", "texto", "card", "note", "nota", "file", "group", "grupo")

        fun normalizeNodeType(raw: String): String = when (raw.lowercase(Locale.ROOT).trim()) {
            "note", "nota", "file" -> "note"
            "group", "grupo" -> "group"
            else -> "text"
        }

        body.lines().forEach { rawLine ->
            val line = rawLine.trim()
            if (line.isEmpty()) return@forEach
            val upper = line.uppercase(Locale.ROOT)
            when {
                upper.startsWith("TITLE:") -> title = line.substringAfter(':').trim()
                upper.startsWith("TITULO:") -> title = line.substringAfter(':').trim()
                upper.startsWith("SUMMARY:") -> summary = line.substringAfter(':').trim()
                upper.startsWith("DESC:") -> summary = line.substringAfter(':').trim()
                upper.startsWith("DESCRIPTION:") -> summary = line.substringAfter(':').trim()
                upper.startsWith("LAYOUT:") -> {
                    val l = line.substringAfter(':').trim().lowercase(Locale.ROOT)
                    layout = when {
                        l in setOf("grid", "grade") -> "grid"
                        l in setOf("radial", "mapa", "mindmap") -> "radial"
                        else -> "tree"
                    }
                }
                upper.startsWith("NODE:") -> {
                    val payload = line.substringAfter(':').trim()
                    val parts = payload.split('|').map { it.trim() }
                    if (parts.isEmpty() || parts.all { it.isBlank() }) return@forEach
                    val autoId = "n${nodes.size + 1}"
                    var id = parts[0].ifBlank { autoId }
                    var nodeType = "text"
                    var colorName: String? = null
                    var nodeTitle = ""
                    var nodeText = ""

                    when {
                        parts.size >= 5 -> {
                            val p1 = parts[1].lowercase(Locale.ROOT)
                            val p2 = parts[2].lowercase(Locale.ROOT)
                            when {
                                p1 in knownTypes && p2 in knownColors -> {
                                    nodeType = normalizeNodeType(p1)
                                    colorName = knownColors[p2]
                                }
                                p1 in knownColors && p2 in knownTypes -> {
                                    colorName = knownColors[p1]
                                    nodeType = normalizeNodeType(p2)
                                }
                                else -> {
                                    if (p1 in knownTypes) nodeType = normalizeNodeType(p1)
                                    if (p2 in knownColors) colorName = knownColors[p2]
                                }
                            }
                            nodeTitle = parts[3]
                            nodeText = parts.drop(4).joinToString(" | ")
                        }
                        parts.size == 4 -> {
                            val p1 = parts[1].lowercase(Locale.ROOT)
                            if (p1 in knownTypes) {
                                nodeType = normalizeNodeType(p1)
                                nodeTitle = parts[2]
                                nodeText = parts[3]
                            } else if (p1 in knownColors) {
                                colorName = knownColors[p1]
                                nodeTitle = parts[2]
                                nodeText = parts[3]
                            } else {
                                nodeTitle = parts[1]
                                nodeText = "${parts[2]} | ${parts[3]}".trim(' ', '|')
                            }
                        }
                        parts.size == 3 -> {
                            nodeTitle = parts[1]
                            nodeText = parts[2]
                        }
                        parts.size == 2 -> {
                            nodeTitle = parts[1]
                        }
                        else -> {
                            id = autoId
                            nodeTitle = parts[0]
                        }
                    }

                    val cleanTitle = nodeTitle.removePrefix("[[").removeSuffix("]]").trim().ifBlank { "Conceito ${nodes.size + 1}" }
                    val cleanText = nodeText.replace("\\n", "\n").trim()
                    nodes.add(
                        GeneratedStudyObject.CanvasNodeSpec(
                            id = id,
                            type = nodeType,
                            title = cleanTitle,
                            text = cleanText,
                            colorName = colorName
                        )
                    )
                }
                upper.startsWith("EDGE:") -> {
                    val payload = line.substringAfter(':').trim()
                    val pipeParts = payload.split('|', limit = 3).map { it.trim() }
                    val linkPart = pipeParts.getOrElse(0) { "" }
                    val arrowSplit = when {
                        linkPart.contains("->") -> linkPart.split("->", limit = 2)
                        linkPart.contains("→") -> linkPart.split("→", limit = 2)
                        pipeParts.size >= 2 -> listOf(pipeParts[0], pipeParts[1])
                        else -> emptyList()
                    }
                    if (arrowSplit.size == 2) {
                        val from = arrowSplit[0].trim().removePrefix("[[").removeSuffix("]]").trim()
                        val to = arrowSplit[1].trim().removePrefix("[[").removeSuffix("]]").trim()
                        val label = when {
                            linkPart.contains("->") || linkPart.contains("→") -> pipeParts.getOrElse(1) { "" }
                            pipeParts.size >= 3 -> pipeParts[2]
                            else -> ""
                        }
                        if (from.isNotBlank() && to.isNotBlank() && !from.equals(to, ignoreCase = true)) {
                            rawEdges.add(Triple(from, to, label.trim()))
                        }
                    }
                }
            }
        }

        if (nodes.isEmpty()) return null
        val idByLowerId = nodes.associate { it.id.lowercase(Locale.ROOT) to it.id }
        val idByLowerTitle = nodes.associate { it.title.lowercase(Locale.ROOT) to it.id }
        val resolvedEdges = rawEdges.mapNotNull { (rawFrom, rawTo, label) ->
            val from = idByLowerId[rawFrom.lowercase(Locale.ROOT)] ?: idByLowerTitle[rawFrom.lowercase(Locale.ROOT)]
            val to = idByLowerId[rawTo.lowercase(Locale.ROOT)] ?: idByLowerTitle[rawTo.lowercase(Locale.ROOT)]
            if (from != null && to != null && from != to) {
                GeneratedStudyObject.CanvasEdgeSpec(from = from, to = to, label = label)
            } else null
        }.distinctBy { Triple(it.from, it.to, it.label) }

        return GeneratedStudyObject.CanvasObj(
            title = title.ifBlank { nodes.first().title.take(40).ifBlank { "Mapa Visual IA" } },
            summary = summary,
            layout = layout,
            nodes = nodes,
            edges = resolvedEdges
        )
    }

