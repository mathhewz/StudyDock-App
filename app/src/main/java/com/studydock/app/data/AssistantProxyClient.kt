    private fun normalizeGoalMetric(
        rawMetric: String,
        rawTarget: String,
        rawUnit: String,
        parsedTarget: Double
    ): String {
        val cleaned = rawMetric
            .substringBefore('(')
            .trim()
            .uppercase()
            .replace('-', '_')
            .replace(' ', '_')
        if (cleaned.isNotBlank()) {
            return when {
                cleaned in setOf("COUNTDOWN", "PRAZO", "CONTAGEM", "DIAS", "DAYS") -> "COUNTDOWN"
                cleaned in setOf("STUDY_HOURS", "HOURS", "HORAS", "HORAS_ESTUDO", "ESTUDO") -> "STUDY_HOURS"
                cleaned in setOf("QUESTIONS", "QUESTOES", "QUESTÕES", "EXERCICIOS", "EXERCÍCIOS") -> "QUESTIONS"
                cleaned in setOf("ACCURACY", "ACURACIA", "ACURÁCIA", "ACERTOS", "PERCENTUAL") -> "ACCURACY"
                cleaned in setOf("PAGES", "PAGINAS", "PÁGINAS", "LEITURA") -> "PAGES"
                cleaned in setOf("FLASHCARDS", "CARDS", "CARTOES", "CARTÕES", "ANKI") -> "FLASHCARDS"
                cleaned in setOf("TASKS", "TAREFAS", "TODO") -> "TASKS"
                cleaned in setOf("HABITS", "HABITOS", "HÁBITOS") -> "HABITS"
                cleaned == "MANUAL" -> "MANUAL"
                else -> if (parsedTarget > 0.0) "MANUAL" else "COUNTDOWN"
            }
        }
        if (parsedTarget <= 0.0) return "COUNTDOWN"
        val hint = "$rawTarget $rawUnit".lowercase()
        return when {
            "hora" in hint || Regex("""\bh\b""").containsMatchIn(hint) -> "STUDY_HOURS"
            "quest" in hint || "exerc" in hint -> "QUESTIONS"
            "%" in hint || "acert" in hint || "acur" in hint -> "ACCURACY"
            "pág" in hint || "pag" in hint -> "PAGES"
            "card" in hint || "anki" in hint || "cart" in hint -> "FLASHCARDS"
            "tarefa" in hint -> "TASKS"
            "hábit" in hint || "habit" in hint -> "HABITS"
            else -> "MANUAL"
        }
    }

