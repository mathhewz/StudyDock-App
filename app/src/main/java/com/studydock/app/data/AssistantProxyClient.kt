enum class FeynmanPersona(val label: String) {
    CHILD("Criança de 10 anos"),
    PEER("Colega de faculdade"),
    ITA_IME("Banca ITA/IME")
}

object FeynmanSocraticEngine {
    private val jargonTerms = listOf(
        "homomorfismo", "isomorfismo", "autovalor", "autovetor", "difeomorfismo",
        "estocástico", "assintótico", "ortogonalidade", "cardinalidade", "compacto",
        "homeomorfismo", "eigenvalue", "lagrangiano", "hamiltoniano", "entropia"
    )

    private val technicalSuffixRegex = Regex("""\b[\p{L}]{7,}(?:morfismo|logia|metria|gonal|variante|diferenci[áa]vel|assint[óo]tic[oa]|estoc[áa]stic[oa]|topol[óo]gic[oa])\b""", RegexOption.IGNORE_CASE)
    private val latexMacroRegex = Regex("""\\([a-zA-Z]{3,})""")

    fun detectJargonWords(explanation: String): List<String> {
        val lower = explanation.lowercase()
        val found = LinkedHashSet<String>()
        jargonTerms.filterTo(found) { it in lower }
        technicalSuffixRegex.findAll(explanation).forEach { found.add(it.value.lowercase()) }
        latexMacroRegex.findAll(explanation).forEach { found.add("\\" + it.groupValues[1]) }
        return found.toList()
    }

    fun buildFeynmanPrompt(topic: String, stage: Int, persona: FeynmanPersona, explanation: String): String {
        val jargon = detectJargonWords(explanation)
        val jargonNote = if (jargon.isNotEmpty()) " Jargões detectados sem definição simples: ${jargon.joinToString(", ")}." else ""
        return "[Feynman Etapa ${stage.coerceIn(1, 4)}/4 | Persona: ${persona.label}] Tópico: $topic. Explicação do aluno: $explanation.$jargonNote Avalie lacunas lógicas e faça 1 pergunta socrática."
    }

    fun buildLeechAtomizerPrompt(front: String, back: String): String =
        "Atomize este flashcard sanguessuga em 2 a 3 cartões mínimos (SuperMemo Minimum Information Principle). Frente: $front | Verso: $back"
}
